// =============================================================================
//  In-memory fakes, hand-written rather than generated by a mocking library.
//
//  A mock framework would express these in fewer lines. It would also express
//  them as a list of expectations at each call site, which for a test about an
//  authorisation rule is exactly the wrong shape: the thing being asserted is
//  "given this guardian link, may this parent read that learner", and that
//  reads far better against a fake holding a set of links than against four
//  Setup(...) calls returning bools.
//
//  Hand-written fakes also fail usefully. A repository method a service calls
//  and the fake does not implement is a compile error, not a silent null.
// =============================================================================

/// <summary>
/// A learner repository over in-memory dictionaries.
/// </summary>
/// <remarks>
/// The guardian links are the interesting part: <see cref="Link"/> is the only
/// way to create one, so a test that wants a parent to see a child has to say
/// so — which mirrors the production rule that a parent sees a child because a
/// staff member created a link row and for no other reason.
/// </remarks>
public sealed class FakeLearnerRepository : ILearnerRepository
{
    private readonly Dictionary<Guid, Learner> learners = [];

    private readonly HashSet<(Guid ParentId, Guid LearnerId)> guardianLinks = [];

    private readonly Dictionary<Guid, List<Guid>> mentorAssignments = [];

    private readonly Dictionary<Guid, List<Guid>> guardianUserIds = [];

    public List<LearnerSummarySnapshot> Snapshots { get; } = [];

    /// <summary>Adds a learner and returns it, so a test can chain.</summary>
    public Learner Add(string reference, int grade = 10, string firstName = "Test", string surname = "Learner")
    {
        var learner = new Learner
        {
            ReferenceCode = reference,
            FirstName = firstName,
            Surname = surname,
            Grade = grade,
            DateOfBirth = new DateOnly(2010, 5, 2),
        };

        learners[learner.Id] = learner;

        return learner;
    }

    public void Link(Guid parentId, Guid learnerId) => guardianLinks.Add((parentId, learnerId));

    public void AssignMentor(Guid mentorId, Guid learnerId)
    {
        if (!mentorAssignments.TryGetValue(mentorId, out var list))
        {
            list = [];
            mentorAssignments[mentorId] = list;
        }

        list.Add(learnerId);
    }

    public void SetGuardianUsers(Guid learnerId, params Guid[] userIds) =>
        guardianUserIds[learnerId] = [.. userIds];

    public Task<Learner?> FindAsync(Guid learnerId, CancellationToken cancellationToken = default) =>
        Task.FromResult(learners.GetValueOrDefault(learnerId));

    public Task<Learner?> FindByReferenceAsync(string referenceCode, CancellationToken cancellationToken = default) =>
        Task.FromResult(learners.Values.FirstOrDefault(l => l.ReferenceCode == referenceCode));

    public Task<bool> IsGuardianOfAsync(Guid parentId, Guid learnerId, CancellationToken cancellationToken = default) =>
        Task.FromResult(guardianLinks.Contains((parentId, learnerId)));

    public Task<IReadOnlyList<LearnerCard>> ForParentAsync(Guid parentId, CancellationToken cancellationToken = default)
    {
        IReadOnlyList<LearnerCard> cards = guardianLinks
            .Where(link => link.ParentId == parentId)
            .Select(link => learners[link.LearnerId])
            .Select(l => new LearnerCard(l.Id, l.ReferenceCode, l.FirstName, l.Surname, l.Grade, l.School, l.Suburb, 0, true))
            .ToList();

        return Task.FromResult(cards);
    }

    public Task<IReadOnlyList<Guid>> LearnerIdsForMentorAsync(Guid mentorId, CancellationToken cancellationToken = default)
    {
        IReadOnlyList<Guid> ids = mentorAssignments.GetValueOrDefault(mentorId, []);

        return Task.FromResult(ids);
    }

    public Task<IReadOnlyList<Guid>> GuardianUserIdsAsync(Guid learnerId, CancellationToken cancellationToken = default)
    {
        IReadOnlyList<Guid> ids = guardianUserIds.GetValueOrDefault(learnerId, []);

        return Task.FromResult(ids);
    }

    public Task<IReadOnlyList<RegisterRow>> RegisterForSessionAsync(Guid sessionId, CancellationToken cancellationToken = default) =>
        Task.FromResult<IReadOnlyList<RegisterRow>>([]);

    public Task<IReadOnlyList<SponsorCard>> SponsorableCardsAsync(int limit, CancellationToken cancellationToken = default) =>
        Task.FromResult<IReadOnlyList<SponsorCard>>([]);

    public Task<Learner> CreateAsync(Learner learner, Guid actorId, CancellationToken cancellationToken = default)
    {
        learners[learner.Id] = learner;

        return Task.FromResult(learner);
    }

    public Task<PagedResult<LearnerCard>> SearchAsync(string? query, int? grade, int page, int pageSize, CancellationToken cancellationToken = default) =>
        Task.FromResult(new PagedResult<LearnerCard>([], 0, page, pageSize));

    public Task<string> NextReferenceCodeAsync(CancellationToken cancellationToken = default) =>
        Task.FromResult($"A-{learners.Count + 1:000}");

    public Task UpsertSummaryAsync(LearnerSummarySnapshot snapshot, CancellationToken cancellationToken = default)
    {
        Snapshots.Add(snapshot);

        return Task.CompletedTask;
    }
}

/// <summary>A mentorship repository over in-memory lists.</summary>
public sealed class FakeMentorshipRepository : IMentorshipRepository
{
    private readonly Dictionary<Guid, MentorAssignment> assignments = [];

    private readonly Dictionary<Guid, Mentor> mentors = [];

    public List<CheckIn> CheckIns { get; } = [];

    public List<MentorAssignment> Added { get; } = [];

    public List<(Guid CheckInId, Guid RecipientUserId)> Escalations { get; } = [];

    public Mentor AddMentor(ClearanceStatus status = ClearanceStatus.Cleared, DateOnly? expiry = null)
    {
        var mentor = new Mentor
        {
            FirstName = "Thandi",
            Surname = "Mokoena",
            Occupation = "Civil engineer",
            ClearanceStatus = status,
            ClearanceExpiry = expiry,
        };

        mentors[mentor.Id] = mentor;

        return mentor;
    }

    public MentorAssignment AddAssignment(
        Mentor mentor,
        Learner learner,
        int schoolYear,
        AssignmentStatus status = AssignmentStatus.Active)
    {
        var assignment = new MentorAssignment
        {
            MentorId = mentor.Id,
            Mentor = mentor,
            LearnerId = learner.Id,
            Learner = learner,
            SchoolYear = schoolYear,
            Status = status,
            ApprovedBy = Guid.CreateVersion7(),
        };

        assignments[assignment.Id] = assignment;

        return assignment;
    }

    public Task<MentorAssignment?> FindAssignmentAsync(Guid assignmentId, CancellationToken cancellationToken = default) =>
        Task.FromResult(assignments.GetValueOrDefault(assignmentId));

    public Task<AssignmentView?> ActiveAssignmentForAsync(Guid learnerId, int schoolYear, CancellationToken cancellationToken = default)
    {
        var match = assignments.Values.FirstOrDefault(a =>
            a.LearnerId == learnerId && a.SchoolYear == schoolYear && a.Status == AssignmentStatus.Active);

        return Task.FromResult(match is null
            ? null
            : new AssignmentView(match.Id, match.MentorId, match.LearnerId, match.SchoolYear, match.Mentor.FullName, match.Mentor.Occupation));
    }

    public Task<IReadOnlyList<MenteeView>> AssignmentsForMentorAsync(Guid mentorId, CancellationToken cancellationToken = default) =>
        Task.FromResult<IReadOnlyList<MenteeView>>([]);

    public Task<Mentor?> FindMentorAsync(Guid mentorId, CancellationToken cancellationToken = default) =>
        Task.FromResult(mentors.GetValueOrDefault(mentorId));

    public void AddAssignment(MentorAssignment assignment)
    {
        assignments[assignment.Id] = assignment;
        Added.Add(assignment);
    }

    public void AddCheckIn(CheckIn checkIn) => CheckIns.Add(checkIn);

    /// <summary>
    /// Honours the flagged filter, because a test asserting the visibility rule
    /// has to exercise it rather than trust it.
    /// </summary>
    public Task<IReadOnlyList<CheckInView>> CheckInsForLearnerAsync(
        Guid learnerId,
        int limit,
        bool includeFlagged,
        CancellationToken cancellationToken = default)
    {
        IReadOnlyList<CheckInView> views = CheckIns
            .Where(c => assignments.GetValueOrDefault(c.AssignmentId)?.LearnerId == learnerId)
            .Where(c => includeFlagged || !c.ConcernFlagged)
            .Take(limit)
            .Select(c => new CheckInView(
                c.Id, c.OccurredOn, c.Mode, c.Wellbeing, c.Notes, c.SupportAreas,
                c.ConcernFlagged, c.EscalatedAt, "Thandi Mokoena", "Civil engineer"))
            .ToList();

        return Task.FromResult(views);
    }

    public Task<IReadOnlyList<ConcernView>> OpenConcernsAsync(CancellationToken cancellationToken = default) =>
        Task.FromResult<IReadOnlyList<ConcernView>>([]);

    public Task<int> CountCheckInsForAssignmentAsync(Guid assignmentId, CancellationToken cancellationToken = default) =>
        Task.FromResult(CheckIns.Count(c => c.AssignmentId == assignmentId));

    public Task MarkEscalatedAsync(Guid checkInId, Guid recipientUserId, CancellationToken cancellationToken = default)
    {
        Escalations.Add((checkInId, recipientUserId));

        return Task.CompletedTask;
    }

    public Task<bool> CloseConcernAsync(Guid checkInId, Guid closedBy, string outcome, CancellationToken cancellationToken = default)
    {
        var checkIn = CheckIns.FirstOrDefault(c => c.Id == checkInId && c.ConcernFlagged && c.ClosedAt is null);

        if (checkIn is null)
        {
            return Task.FromResult(false);
        }

        checkIn.ClosedAt = DateTimeOffset.UnixEpoch;
        checkIn.ClosedBy = closedBy;
        checkIn.Outcome = outcome;

        return Task.FromResult(true);
    }
}

/// <summary>
/// A unit of work that runs the work and records what happened.
/// </summary>
/// <remarks>
/// <para>
/// Deliberately <strong>does not swallow exceptions</strong>. A fake that
/// caught them would make every rollback test pass regardless of the code under
/// test, which is the worst possible property for a fake guarding the
/// safeguarding rollback.
/// </para>
/// <para>
/// It records whether a rollback happened so a test can assert on it, and it
/// reproduces the real nesting rule: an inner transaction joins the outer one.
/// </para>
/// </remarks>
public sealed class FakeUnitOfWork : IUnitOfWork
{
    private int depth;

    public int Saves { get; private set; }

    public int Commits { get; private set; }

    public int Rollbacks { get; private set; }

    public Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        Saves++;

        return Task.FromResult(0);
    }

    public async Task<T> TransactionAsync<T>(Func<Task<T>> work, CancellationToken cancellationToken = default)
    {
        depth++;

        try
        {
            var result = await work();

            if (depth == 1)
            {
                Commits++;
            }

            return result;
        }
        catch
        {
            if (depth == 1)
            {
                Rollbacks++;
            }

            // Rethrown, always. The whole point of the rollback tests is that
            // the exception escapes.
            throw;
        }
        finally
        {
            depth--;
        }
    }

    public async Task TransactionAsync(Func<Task> work, CancellationToken cancellationToken = default) =>
        await TransactionAsync<object?>(async () =>
        {
            await work();

            return null;
        }, cancellationToken);
}

/// <summary>An audit repository that keeps what was written, for assertions.</summary>
public sealed class FakeAuditRepository : IAuditRepository
{
    public List<(Guid? UserId, string Action, string EntityName, string? EntityId, object? Before, object? After)> Entries { get; } = [];

    public void Write(Guid? userId, string action, string entityName, string? entityId, object? before, object? after, string ipAddress, string userAgent) =>
        Entries.Add((userId, action, entityName, entityId, before, after));

    public Task<PagedResult<AuditView>> RecentAsync(int page, int pageSize, CancellationToken cancellationToken = default) =>
        Task.FromResult(new PagedResult<AuditView>([], 0, page, pageSize));

    public Task<IReadOnlyList<AuditView>> ForEntityAsync(string entityName, string entityId, int limit, CancellationToken cancellationToken = default) =>
        Task.FromResult<IReadOnlyList<AuditView>>([]);

    /// <summary>
    /// Whether any audit entry's snapshot contains a given string.
    /// </summary>
    /// <remarks>
    /// Used by the tests that assert a note's text is <em>not</em> copied into
    /// the audit trail. Serialising the anonymous snapshot is the only way to
    /// look inside it, which is also how the production code stores it.
    /// </remarks>
    public bool AnySnapshotContains(string fragment) =>
        Entries.Any(entry =>
            (entry.Before is not null && System.Text.Json.JsonSerializer.Serialize(entry.Before).Contains(fragment, StringComparison.OrdinalIgnoreCase))
            || (entry.After is not null && System.Text.Json.JsonSerializer.Serialize(entry.After).Contains(fragment, StringComparison.OrdinalIgnoreCase)));
}

/// <summary>A dispatcher that records the events raised instead of handling them.</summary>
/// <remarks>
/// Lets a service test assert "exactly one AttendanceRecorded was raised, and it
/// said the learner was present" without standing up three listeners — which is
/// the whole reason the services raise events rather than calling the listeners.
/// </remarks>
public sealed class FakeEventDispatcher : IDomainEventDispatcher
{
    public List<IDomainEvent> Dispatched { get; } = [];

    /// <summary>Set to make the dispatcher throw, simulating a non-advisory listener failing.</summary>
    public Exception? ThrowOn { get; set; }

    public Task DispatchAsync<TEvent>(TEvent domainEvent, CancellationToken cancellationToken)
        where TEvent : IDomainEvent
    {
        Dispatched.Add(domainEvent);

        return ThrowOn is null ? Task.CompletedTask : Task.FromException(ThrowOn);
    }

    public IEnumerable<TEvent> Of<TEvent>() => Dispatched.OfType<TEvent>();
}

