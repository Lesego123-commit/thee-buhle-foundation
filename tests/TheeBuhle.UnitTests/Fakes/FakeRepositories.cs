/// <summary>
/// A password hasher that is fast and obviously fake.
/// </summary>
/// <remarks>
/// The auth tests assert about lockout, token rotation and uniform messages, not
/// about Argon2 — and paying 19 MiB and two passes per assertion would make the
/// suite slow enough that people stop running it. The real hasher has its own
/// tests.
/// </remarks>
public sealed class FakePasswordHasher : IPasswordHasher
{
    public int DummyVerifyCalls { get; private set; }

    public bool RehashNeeded { get; set; }

    public string Hash(string password) => $"fake:{password}";

    public bool Verify(string password, string hash) =>
        string.Equals(hash, $"fake:{password}", StringComparison.Ordinal);

    public bool NeedsRehash(string hash) => RehashNeeded;

    /// <summary>Counted, so a test can assert the timing defence was exercised.</summary>
    public void DummyVerify(string password) => DummyVerifyCalls++;
}
